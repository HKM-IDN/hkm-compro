// Split "150 Mbps" → { num: "150", unit: "Mbps" }
export function splitHighlightValue(val = '') {
  const m = val.match(/^([\d.,]+)\s*(.*)$/);
  if (m) return { num: m[1], unit: m[2] };
  return { num: val, unit: '' };
}
